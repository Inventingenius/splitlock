-- SPLITLOCK — speedrun moderation schema
--
-- Leaderboards surface verified personal-bests of non-banned runners.
-- Bans are reversible flags on the runner; run rows are append-only and
-- never deleted so review history stays intact for appeals.
--
-- Index design follows the hot paths:
--   * DISTINCT ON (runner_id) ORDER BY time_ms  → runs_pb_idx
--   * pending queue by game + recency           → runs_pending_idx
--   * name search                               → runners_name_lower_idx
--   * at most one active ban per runner         → bans_active_runner_idx

CREATE TABLE IF NOT EXISTS games (
  id          INTEGER PRIMARY KEY,
  slug        TEXT NOT NULL UNIQUE,
  name        TEXT NOT NULL,
  short_name  TEXT NOT NULL,
  year        INTEGER NOT NULL,
  platform    TEXT NOT NULL,
  genre       TEXT NOT NULL,
  hue         INTEGER NOT NULL,
  wr_base_ms  INTEGER NOT NULL
);

CREATE TABLE IF NOT EXISTS categories (
  id          INTEGER PRIMARY KEY,
  game_id     INTEGER NOT NULL REFERENCES games(id),
  slug        TEXT NOT NULL,
  name        TEXT NOT NULL,
  rules       TEXT NOT NULL,
  wr_base_ms  INTEGER NOT NULL,
  checkpoints JSONB NOT NULL DEFAULT '[]'::jsonb,
  UNIQUE (game_id, slug)
);

CREATE TABLE IF NOT EXISTS runners (
  id         INTEGER PRIMARY KEY,
  name       TEXT NOT NULL UNIQUE,
  country    TEXT NOT NULL,
  joined_at  TIMESTAMPTZ NOT NULL,
  banned     BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE IF NOT EXISTS moderators (
  id     TEXT PRIMARY KEY,
  name   TEXT NOT NULL,
  handle TEXT NOT NULL,
  title  TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS moderator_games (
  moderator_id TEXT NOT NULL REFERENCES moderators(id),
  game_id      INTEGER NOT NULL REFERENCES games(id),
  PRIMARY KEY (moderator_id, game_id)
);

CREATE TABLE IF NOT EXISTS runs (
  id            INTEGER PRIMARY KEY,
  game_id       INTEGER NOT NULL REFERENCES games(id),
  category_id   INTEGER NOT NULL REFERENCES categories(id),
  runner_id     INTEGER NOT NULL REFERENCES runners(id),
  time_ms       INTEGER NOT NULL,
  status        TEXT NOT NULL CHECK (status IN ('pending', 'verified', 'rejected')),
  platform      TEXT NOT NULL,
  emulator      BOOLEAN NOT NULL DEFAULT FALSE,
  video_url     TEXT,
  comment       TEXT,
  submitted_at  TIMESTAMPTZ NOT NULL,
  verified_at   TIMESTAMPTZ
);

CREATE TABLE IF NOT EXISTS reviews (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id        INTEGER NOT NULL REFERENCES runs(id),
  moderator_id  TEXT REFERENCES moderators(id),
  action        TEXT NOT NULL CHECK (action IN ('submitted', 'approved', 'rejected', 'reopened', 'note')),
  note          TEXT,
  created_at    TIMESTAMPTZ NOT NULL
);

CREATE TABLE IF NOT EXISTS bans (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  runner_id     INTEGER NOT NULL REFERENCES runners(id),
  moderator_id  TEXT NOT NULL REFERENCES moderators(id),
  reason        TEXT NOT NULL,
  created_at    TIMESTAMPTZ NOT NULL,
  lifted_at     TIMESTAMPTZ,
  lift_reason   TEXT,
  lifted_by     TEXT REFERENCES moderators(id)
);

CREATE TABLE IF NOT EXISTS splits (
  id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  run_id        INTEGER NOT NULL REFERENCES runs(id) ON DELETE CASCADE,
  checkpoint    TEXT NOT NULL,
  time_ms       INTEGER NOT NULL,
  order_index   INTEGER NOT NULL
);

-- Covering-ish index for the PB probe:
--   DISTINCT ON (runner_id) … ORDER BY runner_id, time_ms, submitted_at
-- Partial on status='verified' keeps the index small (pending/rejected
-- never appear on leaderboards).
CREATE INDEX IF NOT EXISTS runs_pb_idx
  ON runs (category_id, runner_id, time_ms, submitted_at)
  WHERE status = 'verified';

-- Rank-ordered scan of a board after PBs are reduced.
CREATE INDEX IF NOT EXISTS runs_board_time_idx
  ON runs (category_id, time_ms)
  WHERE status = 'verified';

-- Queue: pending runs for a moderator's assigned games, newest first.
CREATE INDEX IF NOT EXISTS runs_pending_idx
  ON runs (game_id, submitted_at DESC)
  WHERE status = 'pending';

CREATE INDEX IF NOT EXISTS runs_runner_idx
  ON runs (runner_id, submitted_at DESC);

CREATE INDEX IF NOT EXISTS runs_status_idx
  ON runs (status);

CREATE INDEX IF NOT EXISTS reviews_run_idx
  ON reviews (run_id, created_at);

CREATE INDEX IF NOT EXISTS bans_runner_idx
  ON bans (runner_id, created_at DESC);

-- Enforces the invariant "at most one active ban per runner" without a
-- trigger: a second INSERT with lifted_at IS NULL fails the unique check.
CREATE UNIQUE INDEX IF NOT EXISTS bans_active_runner_idx
  ON bans (runner_id)
  WHERE lifted_at IS NULL;

-- Functional index for case-insensitive runner search (LOWER(name) LIKE).
CREATE INDEX IF NOT EXISTS runners_name_lower_idx
  ON runners (lower(name));

CREATE INDEX IF NOT EXISTS splits_run_idx
  ON splits (run_id, order_index);
